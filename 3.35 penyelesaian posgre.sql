CREATE TABLE AIRPLANE (
    Airplane_id VARCHAR(20) NOT NULL,
    Total_no_of_seats INTEGER,
    AIRPLANE_TYPE_Type_name VARCHAR(50) NOT NULL,
    PRIMARY KEY (Airplane_id)
);

CREATE TABLE AIRPLANE_TYPE (
    Type_name VARCHAR(50) NOT NULL,
    Max_seats INTEGER,
    Company VARCHAR(50),
    PRIMARY KEY (Type_name)
);

CREATE TABLE AIRPORT (
    Airport_code VARCHAR(10) NOT NULL,
    City VARCHAR(50),
    State VARCHAR(50),
    Name VARCHAR(100),
    PRIMARY KEY (Airport_code)
);

CREATE TABLE FARE (
    Code VARCHAR(20) NOT NULL,
    Amount INTEGER,
    Restrictions VARCHAR(255),
    FLIGHT_Number VARCHAR(20) NOT NULL,
    PRIMARY KEY (Code)
);

CREATE TABLE FLIGHT (
    Number VARCHAR(20) NOT NULL,
    Airline VARCHAR(50),
    Weekdays VARCHAR(20),
    PRIMARY KEY (Number)
);

CREATE TABLE FLIGHT_LEG (
    Leg_no INTEGER NOT NULL,
    Scheduled_dep_time VARCHAR(50),
    Scheduled_arr_time VARCHAR(50),
    FLIGHT_Number VARCHAR(20) NOT NULL,
    AIRPORT_Airport_code2 VARCHAR(10) NOT NULL,
    AIRPORT_Airport_code VARCHAR(10) NOT NULL,
    PRIMARY KEY (Leg_no)
);

CREATE TABLE LEG_INSTANCE (
